import { build } from 'esbuild';
import { builtinModules } from 'node:module';
import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, stat, writeFile } from 'node:fs/promises';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const outputDirectory = join(root, 'bundle');
const check = process.argv.includes('--check');
const hash = data => createHash('sha256').update(data).digest('hex');
const pathKey = path => relative(root, path).split(sep).join('/');

const built = await build({
  absWorkingDir: root,
  entryPoints: { server: 'src/index.ts', tools: 'src/api.ts' },
  outdir: 'bundle',
  outExtension: { '.js': '.cjs' },
  bundle: true,
  platform: 'node',
  format: 'cjs',
  target: 'node22',
  minify: true,
  legalComments: 'eof',
  metafile: true,
  write: false,
  logLevel: 'warning',
});

// A shipped bundle must depend only on Node built-ins, never node_modules.
for (const output of Object.values(built.metafile.outputs)) {
  for (const dependency of output.imports) {
    if (dependency.external && !builtinModules.includes(dependency.path.replace(/^node:/, ''))) {
      throw new Error('Unbundled runtime dependency: ' + dependency.path);
    }
  }
}

const packages = new Map();
const inputs = {};
for (const input of Object.keys(built.metafile.inputs).sort()) {
  const absolute = resolve(root, input);
  if (!input.includes('node_modules/')) {
    inputs[pathKey(absolute)] = hash(await readFile(absolute));
    continue;
  }
  let directory = dirname(absolute);
  while (directory !== root && directory !== dirname(directory)) {
    let pkg;
    try {
      pkg = JSON.parse(await readFile(join(directory, 'package.json'), 'utf8'));
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
    }
    if (pkg?.name && pkg?.version) {
      packages.set(directory, pkg);
      break;
    }
    directory = dirname(directory);
  }
}
for (const name of ['package.json', 'package-lock.json', 'tsconfig.json', 'build-plugin.mjs', 'mcp.mjs', 'run-tool.mjs']) {
  inputs[name] = hash(await readFile(join(root, name)));
}

const notices = ['Third-party notices for the bundled Material Theme runtime.', 'Generated by build-plugin.mjs from the packages included by esbuild.', ''];
const dependencies = [];
for (const [directory, pkg] of [...packages].sort((a, b) => a[1].name < b[1].name ? -1 : 1)) {
  dependencies.push({ name: pkg.name, version: pkg.version, license: pkg.license });
  notices.push('=== ' + pkg.name + '@' + pkg.version + ' (' + pkg.license + ') ===', '');
  const licenseFiles = (await readdir(directory)).filter(name => /^(licen[sc]e|copying|notice)([.-]|$)/i.test(name)).sort();
  if (licenseFiles.length === 0) throw new Error('Missing license notice for ' + pkg.name);
  for (const name of licenseFiles) {
    const path = join(directory, name);
    if ((await stat(path)).isFile()) notices.push(await readFile(path, 'utf8'), '');
  }
}

const artifacts = new Map(built.outputFiles.map(file => [file.path, file.contents]));
artifacts.set(join(outputDirectory, 'THIRD_PARTY_NOTICES.txt'), Buffer.from(notices.join('\n') + '\n'));
const metadata = {
  node: '>=22',
  inputs: Object.fromEntries(Object.entries(inputs).sort(([a], [b]) => a < b ? -1 : 1)),
  dependencies,
  outputs: Object.fromEntries([...artifacts].map(([path, bytes]) => [pathKey(path), hash(bytes)])),
};
artifacts.set(join(outputDirectory, 'manifest.json'), Buffer.from(JSON.stringify(metadata, null, 2) + '\n'));

if (!check) await mkdir(outputDirectory, { recursive: true });
for (const [path, bytes] of artifacts) {
  if (check) {
    const existing = await readFile(path).catch(error => {
      if (error.code === 'ENOENT') return null;
      throw error;
    });
    if (!existing || !existing.equals(Buffer.from(bytes))) {
      throw new Error('Bundle is missing or stale: ' + pathKey(path) + '. Run npm run build.');
    }
  } else {
    await writeFile(path, bytes);
  }
}
console.log(check ? 'Plugin bundles match the source and lockfile.' : 'Built standalone MCP server and tool helper with third-party notices.');
